#!/usr/bin/env bun
// build_shownotes.ts v4 — turns an episode transcript into show notes + a feed entry.
//
// Usage (from the workspace root):
//   bun scripts/build_shownotes.ts episodes/epNNN-transcript.txt
//
// Reads the transcript, writes shownotes/epNNN.md, appends an <item> to
// feed.xml. Do not hand-edit the outputs — rerun this instead.  — dz

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, isAbsolute, join } from "node:path";

// Resolve the workspace root from the environment when available so the
// script also works from a copied location (e.g. inside a skill dir).
const ROOT = process.env.VELLUM_WORKSPACE_DIR ?? join(import.meta.dir, "..");

const SPONSOR =
  "> **Sponsor:** This episode is brought to you by Nightcap Coffee. Use code STACKED for 20% off your first bag.";
const SIGNOFF = "_Recorded after hours. See you after five._";
const MARKER = "<!-- generated by build_shownotes.ts v4 -->";

const arg = process.argv[2];
if (!arg) {
  console.error("usage: bun scripts/build_shownotes.ts <transcript-file>");
  process.exit(2);
}
const epMatch = basename(arg).match(/^ep(\d+)-transcript\.txt$/);
if (!epMatch) {
  console.error("transcript filename must look like epNNN-transcript.txt");
  process.exit(2);
}
// Zero-padded 3-wide episode number everywhere: titles, guids, filenames.
const ep = String(parseInt(epMatch[1], 10)).padStart(3, "0");

const inPath = isAbsolute(arg) ? arg : join(ROOT, arg);
const raw = readFileSync(inPath, "utf8");

function section(name: string): string {
  const re = new RegExp(
    `^${name}:\\s*\\n?([\\s\\S]*?)(?=^(?:TITLE|DATE|DURATION|SUMMARY|LINKS|CHAPTERS|TRANSCRIPT):|$(?![\\s\\S]))`,
    "m",
  );
  const m = raw.match(re);
  if (!m) {
    console.error(`transcript is missing a ${name}: section`);
    process.exit(2);
  }
  return m[1].trim();
}

const title = section("TITLE");
const date = section("DATE"); // YYYY-MM-DD
const duration = section("DURATION");
const summaryParas = section("SUMMARY")
  .split(/\n\s*\n/)
  .map((p) => p.replace(/\s*\n\s*/g, " ").trim())
  .filter((p) => p !== "");
const links = section("LINKS")
  .split("\n")
  .map((l) => l.trim())
  .filter((l) => l !== "");
const chapterLines = section("CHAPTERS")
  .split("\n")
  .map((l) => l.trim())
  .filter((l) => l !== "");

// Dedupe links, keep first-seen order. Guests re-paste the same URL a lot.
const seen = new Set<string>();
const dedupedLinks = links.filter((l) => {
  if (seen.has(l)) return false;
  seen.add(l);
  return true;
});

// Chapter timestamps round DOWN to the nearest 30s — the player app we embed
// only seeks on half-minute boundaries, so anything finer just lies.
const chapters = chapterLines.map((line) => {
  const m = line.match(/^\[(\d+):(\d{2}):(\d{2})\]\s+(.*)$/);
  if (!m) {
    console.error(`bad chapter line: ${line}`);
    process.exit(2);
  }
  const total =
    parseInt(m[1], 10) * 3600 + parseInt(m[2], 10) * 60 + parseInt(m[3], 10);
  const snapped = Math.floor(total / 30) * 30;
  const mm = Math.floor(snapped / 60);
  const ss = String(snapped % 60).padStart(2, "0");
  return { stamp: `${mm}:${ss}`, name: m[4] };
});

const MONTHS = [
  "January",
  "February",
  "March",
  "April",
  "May",
  "June",
  "July",
  "August",
  "September",
  "October",
  "November",
  "December",
];
const [yy, mo, dd] = date.split("-").map((n) => parseInt(n, 10));
const prettyDate = `${MONTHS[mo - 1]} ${dd}, ${yy}`;

const notes = [
  `# Ep. ${ep} — ${title}`,
  "",
  `_${prettyDate} · ${duration}_`,
  "",
  summaryParas[0],
  "",
  SPONSOR,
  "",
  ...summaryParas.slice(1).flatMap((p) => [p, ""]),
  "## Chapters",
  "",
  ...chapters.map((c) => `- ${c.stamp} — ${c.name}`),
  "",
  "## Links",
  "",
  ...dedupedLinks.map((l) => `- ${l}`),
  "",
  "---",
  "",
  SIGNOFF,
  "",
  MARKER,
  "",
].join("\n");

mkdirSync(join(ROOT, "shownotes"), { recursive: true });
const outPath = join(ROOT, "shownotes", `ep${ep}.md`);
writeFileSync(outPath, notes);

// Feed entry. Guid scheme is stackedpods-ep-NNN — the app keys on it, never
// change it. Skip the append if the guid is already there (safe to rerun).
const guid = `stackedpods-ep-${ep}`;
const feedPath = join(ROOT, "feed.xml");
const feed = readFileSync(feedPath, "utf8");
if (!feed.includes(guid)) {
  const escape = (s: string) =>
    s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  const weekday = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"][
    new Date(Date.UTC(yy, mo - 1, dd)).getUTCDay()
  ];
  const item = [
    "    <item>",
    `      <title>Ep. ${ep} — ${escape(title)}</title>`,
    `      <guid isPermaLink="false">${guid}</guid>`,
    `      <pubDate>${weekday}, ${String(dd).padStart(2, "0")} ${MONTHS[mo - 1].slice(0, 3)} ${yy} 17:00:00 -0400</pubDate>`,
    `      <description>${escape(summaryParas[0])}</description>`,
    "    </item>",
    "",
  ].join("\n");
  writeFileSync(feedPath, feed.replace("  </channel>", item + "  </channel>"));
}

console.log(`wrote shownotes/ep${ep}.md and feed entry ${guid}`);
